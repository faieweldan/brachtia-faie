export function flagFor(iso: string) {
  return String.fromCodePoint(
    ...iso
      .toUpperCase()
      .split("")
      .map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

export function countryByIso(iso: string) {
  return COUNTRIES.find((c) => c.iso === iso);
}
